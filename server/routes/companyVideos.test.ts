import express, { type NextFunction, type Request, type Response } from "express";
import type { Server } from "node:http";
import { MySqlDialect } from "drizzle-orm/mysql-core";
import type { SQL } from "drizzle-orm";
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import type { z } from "zod";

const mocks = vi.hoisted(() => ({
  select: vi.fn(), insert: vi.fn(), update: vi.fn(), remove: vi.fn(), allowKey: vi.fn(),
}));
vi.mock("../db", async () => ({
  db: { select: mocks.select, insert: mocks.insert, update: mocks.update, delete: mocks.remove },
  schema: await import("../../drizzle/schema"), newId: () => "new-video",
}));
vi.mock("../billing", () => ({ allowKey: mocks.allowKey }));
vi.mock("../appSettings", () => ({ setting: () => 20 }));
vi.mock("../storage", async () => {
  const { default: multer } = await import("multer");
  return { UPLOAD_DIR: ".", diskUpload: () => multer({ storage: multer.memoryStorage() }) };
});
vi.mock("./auth", () => ({
  h: (handler: (req: Request, res: Response) => Promise<unknown>) => (req: Request, res: Response, next: NextFunction) => handler(req, res).catch(next),
  parse: (schema: z.ZodType, input: unknown, res: Response) => {
    const parsed = schema.safeParse(input);
    if (parsed.success) return parsed.data;
    res.status(400).json({ error: parsed.error.message });
  },
}));
const { default: router } = await import("./companyVideos");

const records = [
  { id: "upload", source: "file", title: "Subscriber lesson", placements: [{ pathId: "modeller", step: "" }], uploadedByName: "Team" },
  { id: "youtube", source: "youtube", title: "Public YouTube lesson", url: "dQw4w9WgXcQ", views: 9, placements: [{ pathId: "modeller", step: "" }], uploadedByName: "Admin" },
  { id: "vimeo", source: "vimeo", title: "Public Vimeo lesson", url: "76979871", views: 4, placements: [], uploadedByName: "Admin" },
];
const dialect = new MySqlDialect();
const filters: { sql: string; params: unknown[] }[] = [];
const inserted = vi.fn();
const updated = vi.fn();
const deleted = vi.fn();
let admin = true;
let server: Server;
let origin: string;
const metadata = { title: "Training video", description: "Description", topic: "ISO 19650 basics", lang: "en", placements: [{ pathId: "modeller", step: "" }] };
const json = (method: string, body: unknown) => ({ method, headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });

// The mock database evaluates the id/source predicates generated by Drizzle, so tests exercise real routing,
// multipart parsing and query scoping without connecting to or changing a deployment.
const rowsFor = (condition: SQL) => {
  const query = dialect.sqlToQuery(condition);
  filters.push(query);
  const hasId = query.sql.includes("`company_videos`.`id`");
  const sources = hasId ? query.params.slice(1) : query.params;
  return records.filter((v) => sources.includes(v.source) && (!hasId || query.params[0] === v.id));
};

beforeAll(async () => {
  const app = express();
  app.use(express.json());
  app.use((req, _res, next) => { req.user = { id: "user", role: admin ? "admin" : "user" } as Request["user"]; next(); });
  app.use(router);
  server = await new Promise<Server>((resolve) => { const listener = app.listen(0, "127.0.0.1", () => resolve(listener)); });
  const address = server.address();
  if (!address || typeof address === "string") throw new Error("Missing test server port");
  origin = `http://127.0.0.1:${address.port}`;
});
afterAll(async () => { await new Promise<void>((resolve, reject) => server.close((e) => e ? reject(e) : resolve())); });
beforeEach(() => {
  vi.clearAllMocks();
  filters.length = 0;
  admin = true;
  mocks.allowKey.mockResolvedValue(true);
  mocks.select.mockImplementation(() => {
    let result: typeof records = [];
    const query = {
      from: () => query, leftJoin: () => query,
      where: (condition: SQL) => { result = rowsFor(condition); return query; },
      orderBy: () => Promise.resolve(result),
      then: (resolve: (rows: typeof records) => unknown) => Promise.resolve(result).then(resolve),
    };
    return query;
  });
  mocks.insert.mockReturnValue({ values: inserted.mockResolvedValue(undefined) });
  mocks.update.mockReturnValue({ set: (value: unknown) => ({ where: (condition: SQL) => { updated(value, rowsFor(condition)); return Promise.resolve(); } }) });
  mocks.remove.mockReturnValue({ where: (condition: SQL) => { deleted(rowsFor(condition)); return Promise.resolve(); } });
});

describe("video collections", () => {
  it("moves existing public links into the free library without changing views, ids or placements", async () => {
    const ours = await fetch(origin + "/company-videos");
    expect(ours.status).toBe(200);
    expect((await ours.json()).videos).toEqual([records[0]]);
    const library = await fetch(origin + "/video-library");
    expect(library.status).toBe(200);
    expect((await library.json()).videos).toEqual(records.slice(1));
    expect(filters.map((q) => q.params)).toEqual([["file"], ["youtube", "vimeo"]]);
    expect(mocks.insert).not.toHaveBeenCalled();
    expect(mocks.remove).not.toHaveBeenCalled();
  });

  it("blocks paid list, file range requests and view counts while public links remain accessible", async () => {
    mocks.allowKey.mockImplementation(async (_req: Request, res: Response) => { res.status(402).json({ error: "Subscription required" }); return false; });
    for (const [path, method] of [["/company-videos", "GET"], ["/company-videos/upload/file", "GET"], ["/company-videos/upload/view", "POST"]]) {
      expect((await fetch(origin + path, { method, headers: { Range: "bytes=0-9" } })).status).toBe(402);
    }
    expect(mocks.select).not.toHaveBeenCalled();
    expect((await fetch(origin + "/video-library")).status).toBe(200);
    expect((await fetch(origin + "/video-library/youtube/view", { method: "POST" })).status).toBe(200);
    expect(updated.mock.calls[0][1]).toEqual([records[1]]);
  });

  it("rejects public links in Our videos and accepts YouTube and Vimeo links only in Video library", async () => {
    const rejected = await fetch(origin + "/company-videos", json("POST", { ...metadata, link: "https://youtu.be/dQw4w9WgXcQ" }));
    expect(rejected.status).toBe(400);
    expect((await rejected.json()).error).toContain("Video library");
    expect(inserted).not.toHaveBeenCalled();
    for (const [source, id, link] of [["youtube", "dQw4w9WgXcQ", "https://youtu.be/dQw4w9WgXcQ"], ["vimeo", "76979871", "https://vimeo.com/76979871"]]) {
      expect((await fetch(origin + "/video-library", json("POST", { ...metadata, link }))).status).toBe(201);
      expect(inserted).toHaveBeenLastCalledWith(expect.objectContaining({ ...metadata, source, url: id }));
    }
    expect((await fetch(origin + "/video-library", json("POST", { ...metadata, link: "https://example.com/video" }))).status).toBe(400);
  });

  it("continues accepting uploaded subscriber training files", async () => {
    const form = new FormData();
    for (const [key, value] of Object.entries(metadata)) form.set(key, typeof value === "string" ? value : JSON.stringify(value));
    form.set("file", new Blob(["video bytes"], { type: "video/mp4" }), "lesson.mp4");
    expect((await fetch(origin + "/company-videos", { method: "POST", body: form })).status).toBe(201);
    expect(inserted).toHaveBeenCalledWith(expect.objectContaining({ source: "file", fileName: "lesson.mp4", mimeType: "video/mp4", size: 11 }));
  });

  it("prevents editing or deleting entries through the wrong collection", async () => {
    for (const path of ["/company-videos/youtube", "/video-library/upload"]) {
      expect((await fetch(origin + path, json("PUT", metadata))).status).toBe(404);
      expect((await fetch(origin + path, { method: "DELETE" })).status).toBe(404);
    }
    expect(updated).not.toHaveBeenCalled();
    expect(deleted).not.toHaveBeenCalled();
    expect((await fetch(origin + "/video-library/vimeo", json("PUT", metadata))).status).toBe(200);
    expect(updated.mock.calls[0][1]).toEqual([records[2]]);
    expect((await fetch(origin + "/video-library/youtube", { method: "DELETE" })).status).toBe(200);
    expect(deleted).toHaveBeenCalledWith([records[1]]);
  });

  it("only lets administrators manage either collection", async () => {
    admin = false;
    for (const path of ["/company-videos", "/video-library"]) {
      expect((await fetch(origin + path, json("POST", metadata))).status).toBe(403);
      expect((await fetch(origin + path + "/youtube", json("PUT", metadata))).status).toBe(403);
      expect((await fetch(origin + path + "/youtube", { method: "DELETE" })).status).toBe(403);
    }
    expect(mocks.select).not.toHaveBeenCalled();
    expect(mocks.insert).not.toHaveBeenCalled();
  });
});
